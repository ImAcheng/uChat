using AntdUI;
using System.Runtime.InteropServices;
using uChat_Desktop.MainApp.Pages;
using uChat_Desktop.Service;

namespace uChat_Desktop.MainApp {
    public partial class FormMain : Window {
        public FormMain() {
            InitializeComponent();
        }

        // objects
        public static FormMain instance;

        // pages
        private MainPage? mainPage;

        private void FormMain_Load(object sender, EventArgs e) {
            instance = this;
            mainPage = new MainPage() {
                Parent = panelMain,
                Dock = DockStyle.Fill
            };
        }

        private async void FormMain_FormClosing(object sender, FormClosingEventArgs e) {
            await ApiService.CloseAllWebSockets();
            Application.Exit();
        }

        #region Window process
        // use lazy render to prevent window from dying.
        private void FormMain_ResizeBegin(object sender, EventArgs e) {
            panelMain.SuspendLayout();
        }

        private void FormMain_ResizeEnd(object sender, EventArgs e) {
            panelMain.ResumeLayout(true);
            panelMain.PerformLayout();
        }


        // disable focus highlight (at some point)
        // this code below are totally generated by AI
        // because I don't think it's important
        // it's just a visual effect problem :D
        // anyway, it calls Windows API to 
        private const int WM_CHANGEUISTATE = 0x0127;
        private const int UIS_SET = 1;
        private const int UISF_HIDEFOCUS = 0x1;

        [DllImport("user32.dll", CharSet = CharSet.Auto)]
        private static extern IntPtr SendMessage(IntPtr hWnd, int msg, int wParam, int lParam);

        protected override void OnLoad(EventArgs e) {
            base.OnLoad(e);
            // Tells Windows to hide focus rectangles for all controls on this form
            SendMessage(this.Handle, WM_CHANGEUISTATE, MakeLong(UIS_SET, UISF_HIDEFOCUS), 0);
        }

        private static int MakeLong(int low, int high) {
            return (high << 16) | (low & 0xffff);
        }

        // deal with control blinking
        protected override CreateParams CreateParams {
            get {
                CreateParams cp = base.CreateParams;
                cp.ExStyle |= 0x02000000; // WS_EX_COMPOSITED
                return cp;
            }
        }
        #endregion
    }
}
